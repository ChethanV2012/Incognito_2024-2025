let activeCard = null;

function showEvents(type) {
  const container = document.getElementById("event-container");
  container.innerHTML = "";

  events[type].forEach((event, index) => {
    const card = document.createElement("div");
    card.className = "event-card";
    card.style.animationDelay = `${index * 0.2}s`;

    card.innerHTML = `
      <div class="event-card-inner">
        <div class="event-card-front">
          <img src="${event.image}" alt="${event.name}">
          <h3>${event.name}</h3>
        </div>
        <div class="event-card-back">
      
          
           <ul>
              ${event.rules.map(rule => `<li>${rule}</li>`).join("")}
            </ul>
            <div class="coordinators">
            <div class="faculty-coordinators">
              <strong>Faculty Coordinator:</strong> ${event.facultyCoordinators}
            </div>
            <div class="student-coordinators">
              <strong>Student Coordinator:</strong> ${event.studentCoordinators}
            </div>
          </div>
          <button onclick="registerEvent('${event.name}')">Register Now</button>
        </div>
      </div>
    `;

    card.addEventListener('click', (e) => {
      if (!e.target.closest('button')) {
        if (activeCard && activeCard !== card) {
          activeCard.classList.remove('active');
        }
        card.classList.toggle('active');
        activeCard = card.classList.contains('active') ? card : null;
      }
    });

    container.appendChild(card);
  });
}

function registerEvent(eventName) {
  // Add your registration logic here
  console.log(`Registering for: ${eventName}`);
  window.location.href = "../registrations/register.html?event=" + encodeURIComponent(eventName);

}

document.addEventListener("DOMContentLoaded", () => {
  showEvents('technical');
});